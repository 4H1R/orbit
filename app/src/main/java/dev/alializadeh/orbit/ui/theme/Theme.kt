package dev.alializadeh.orbit.ui.theme

import android.content.Context
import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.material3.ColorScheme
import androidx.compose.material3.MaterialExpressiveTheme
import androidx.compose.material3.dynamicDarkColorScheme
import androidx.compose.material3.dynamicLightColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.runtime.CompositionLocalProvider
import androidx.compose.runtime.remember
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.platform.LocalConfiguration
import androidx.compose.ui.platform.LocalContext
import com.materialkolor.PaletteStyle
import com.materialkolor.dynamiccolor.ColorSpec
import com.materialkolor.ktx.harmonize
import com.materialkolor.material3.dynamicColorScheme
import com.materialkolor.material3.rememberDynamicColorScheme
import dev.alializadeh.orbit.calendar.CalendarSystem
import dev.alializadeh.orbit.format.LocalOrbitFormats
import dev.alializadeh.orbit.format.OrbitFormats
import dev.alializadeh.orbit.language.OrbitLanguage

/** What the theme is built from: the Appearance preferences. */
data class OrbitAppearance(
    val themeMode: ThemeMode = ThemeMode.System,
    val colourSource: ColourSource = ColourSource.OrbitViolet,
    /** The "Your colour" seed; used when [colourSource] is [ColourSource.Custom]. */
    val customSeed: Color? = null,
)

/**
 * Orbit's Material 3 Expressive theme, plus the formatters every screen reads through
 * [LocalOrbitFormats].
 *
 * - Light or dark follows [OrbitAppearance.themeMode] (System follows the phone).
 * - Orbit violet and Your colour: a TonalSpot scheme generated by MaterialKolor (SPEC_2025) from
 *   the seed. Match wallpaper: Android's dynamic scheme.
 * - Apricot, the Important-date accent, is the tertiary colour in every case, harmonised towards
 *   the scheme's primary so it sits well with any seed.
 * - Digits: Persian in the Persian UI unless [useLatinDigits]. Dates show in [primaryCalendar].
 */
@Composable
fun OrbitTheme(
    appearance: OrbitAppearance = OrbitAppearance(),
    useLatinDigits: Boolean = false,
    /** Null: the UI language's own (Persian → Solar Hijri), as before first run sets it. */
    primaryCalendar: CalendarSystem? = null,
    /** The Lunar date adjustment in force: a change gives new formats, so every date is drawn again. */
    lunarAdjustmentDays: Int = 0,
    content: @Composable () -> Unit,
) {
    val darkTheme = appearance.themeMode.isDark()
    val colorScheme = when (appearance.colourSource) {
        ColourSource.OrbitViolet -> seededScheme(OrbitViolet, darkTheme)
        ColourSource.Custom -> seededScheme(appearance.customSeed ?: OrbitViolet, darkTheme)
        ColourSource.Wallpaper -> wallpaperScheme(darkTheme)
    }
    val context = LocalContext.current
    val typography = remember(context) { orbitTypography(OrbitFonts.get(context)) }
    val language = OrbitLanguage.of(LocalConfiguration.current.locales[0])
    val calendar = primaryCalendar ?: language.defaultCalendar
    val formats = remember(language, useLatinDigits, calendar, lunarAdjustmentDays) {
        OrbitFormats(language, useLatinDigits, calendar, lunarAdjustmentDays)
    }
    CompositionLocalProvider(LocalOrbitFormats provides formats) {
        MaterialExpressiveTheme(
            colorScheme = colorScheme,
            typography = typography,
            content = content,
        )
    }
}

@Composable
private fun seededScheme(seed: Color, darkTheme: Boolean): ColorScheme = rememberDynamicColorScheme(
    seedColor = seed,
    isDark = darkTheme,
    tertiary = Apricot.harmonize(seed),
    style = PaletteStyle.TonalSpot,
    specVersion = ColorSpec.SpecVersion.SPEC_2025,
)

/** The wallpaper scheme with its tertiary roles replaced by apricot, harmonised to its primary. */
@Composable
private fun wallpaperScheme(darkTheme: Boolean): ColorScheme {
    val context = LocalContext.current
    val wallpaper = if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
    val apricotRoles = seededScheme(wallpaper.primary, darkTheme)
    return wallpaper.copy(
        tertiary = apricotRoles.tertiary,
        onTertiary = apricotRoles.onTertiary,
        tertiaryContainer = apricotRoles.tertiaryContainer,
        onTertiaryContainer = apricotRoles.onTertiaryContainer,
        tertiaryFixed = apricotRoles.tertiaryFixed,
        tertiaryFixedDim = apricotRoles.tertiaryFixedDim,
        onTertiaryFixed = apricotRoles.onTertiaryFixed,
        onTertiaryFixedVariant = apricotRoles.onTertiaryFixedVariant,
    )
}

/** Whether this Theme setting means dark right now (System follows the phone). */
@Composable
fun ThemeMode.isDark(): Boolean = when (this) {
    ThemeMode.System -> isSystemInDarkTheme()
    ThemeMode.Light -> false
    ThemeMode.Dark -> true
}

/**
 * Orbit's colour scheme outside composition (the home-screen widget): the same rules as
 * [OrbitTheme] for [appearance], light or [darkTheme].
 */
fun orbitColorScheme(context: Context, appearance: OrbitAppearance, darkTheme: Boolean): ColorScheme {
    fun seeded(seed: Color) = dynamicColorScheme(
        seedColor = seed,
        isDark = darkTheme,
        tertiary = Apricot.harmonize(seed),
        style = PaletteStyle.TonalSpot,
        specVersion = ColorSpec.SpecVersion.SPEC_2025,
    )
    return when (appearance.colourSource) {
        ColourSource.OrbitViolet -> seeded(OrbitViolet)
        ColourSource.Custom -> seeded(appearance.customSeed ?: OrbitViolet)
        ColourSource.Wallpaper -> {
            val wallpaper = if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
            val apricotRoles = seeded(wallpaper.primary)
            wallpaper.copy(
                tertiary = apricotRoles.tertiary,
                onTertiary = apricotRoles.onTertiary,
                tertiaryContainer = apricotRoles.tertiaryContainer,
                onTertiaryContainer = apricotRoles.onTertiaryContainer,
            )
        }
    }
}
